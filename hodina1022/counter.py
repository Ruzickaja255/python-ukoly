# počítadlo od 1 do 10
pocitadlo=1 # inicializace
while pocitadlo <= 10: # podmínka, která musí po celou dobu platit, aby se cyklus opakoval
    print(f"{pocitadlo}.")
    pocitadlo += 1 # změna proměnné, která čítá nahoru (inkrementace)

pocitadlo=10
while pocitadlo > 0:
    print(f"{pocitadlo}.")
    pocitadlo -= 1 # změna proměnné, která čítá dolů (dekrementace)